function useIpaPlayback() {
  const audioRef = useRef(null)
  const [message, setMessage] = useState('')
  const stop = () => {
    if (!audioRef.current) return
    const audio = audioRef.current
    audioRef.current = null
    audio.onended = null
    audio.onerror = null
    audio.onplaying = null
    audio.pause()
    audio.removeAttribute('src')
    audio.load()
  }
  useEffect(() => () => {
    if (audioRef.current) {
      audioRef.current.pause()
      audioRef.current.removeAttribute('src')
    }
  }, [])
  const play = (sound, l) => {
    stop()
    setMessage('')
    const audio = new Audio(`${import.meta.env.BASE_URL}audio/ipa-one-voice/${sound.audioFile}`)
    audioRef.current = audio
    const failed = () => {
      if (audioRef.current !== audio) return
      audioRef.current = null
      setMessage(l.unavailable)
    }
    audio.onplaying = () => {
      if (audioRef.current === audio) setMessage(l.playingRecording)
    }
    audio.onended = () => {
      if (audioRef.current !== audio) return
      audioRef.current = null
      setMessage('')
    }
    audio.onerror = failed
    try { audio.play().catch(failed) } catch { failed() }
  }
  return { play, stop, message }
}

function SoundButton({ sound, l, play, className = '' }) {
  return <button type="button" className={`ipa-play ${className}`}
    onClick={() => play(sound, l)}
    aria-label={`${l.listen}: /${sound.ipa}/, ${sound.word}`}>
    <Glyph name="play" size={15}/><span>{l.listen}</span>
  </button>
}

function SourceDisclosure({ l }) {
  return <details className="ipa-sources">
    <summary>{l.source}</summary>
    <p>{l.recordingNote}</p>
    <p>
      <a href={IPA_VOICE_SOURCE} target="_blank" rel="noopener noreferrer">{l.voiceModel}</a>
      {' · '}
      <a href="https://keithito.com/LJ-Speech-Dataset/" target="_blank"
        rel="noopener noreferrer">{l.dataset}</a>
    </p>
  </details>
}

