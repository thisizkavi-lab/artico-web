import { useEffect, useRef, useState } from 'react'
import { useLanguage } from './Language'
import { Glyph } from './LessonExperience'
import './ipa-voice-pilot.css'

// One voice for every sample. These are generated words, not isolated phonemes.
export const voiceSamples = [
  { ipa: 'i', word: 'seat' }, { ipa: 'ɪ', word: 'sit' },
  { ipa: 'θ', word: 'thin' }, { ipa: 'ð', word: 'this' },
  { ipa: 'ʃ', word: 'ship' }, { ipa: 'ʒ', word: 'vision' },
  { ipa: 'æ', word: 'cat' }, { ipa: 'ʌ', word: 'cup' },
  { ipa: 'ɝ', word: 'bird' }, { ipa: 'ɚ', word: 'teacher' },
  { ipa: 'oʊ', word: 'go' }, { ipa: 'ɔɪ', word: 'boy' },
]
export const pilotAudioUrl = word => `${import.meta.env.BASE_URL}audio/ipa-voice-pilot/${word}.wav`

const labels = {
  en: {
    title: 'One American voice · audio experiment',
    intro: 'Listen to 12 example words generated by the same U.S.-English voice. This is a voice-quality test, not our final IPA collection.',
    button: 'Listen', stop: 'Stop', playing: 'Playing',
    instruction: 'Compare seat /i/ with sit /ɪ/, and thin /θ/ with this /ð/. The recording contains the whole word, not only the IPA sound.',
    note: 'Generated offline with Piper en_US-ljspeech-medium, trained on the public-domain LJ Speech dataset. We still need to review the pronunciation before using these as teaching models.',
    error: 'The sample could not play here. Open the source WAV instead.',
    source: 'About the voice and source dataset', wav: 'Open WAV',
  },
  ja: {
    title: '同じアメリカ英語の声 · 音声実験',
    intro: '１人のアメリカ英語の音声モデルで作った12語を試せます。正式なIPA音源ではなく、音質を確かめるためのテストです。',
    button: '聞く', stop: '停止', playing: '再生中',
    instruction: 'seat /i/ と sit /ɪ/、thin /θ/ と this /ð/ を聞き比べましょう。音声は記号だけでなく、単語全体を読みます。',
    note: '公開利用できるLJ Speechを使って学習したPiperのen_US-ljspeech-mediumで作りました。教材用には発音の確認が必要です。',
    error: '音声を再生できませんでした。元のWAVを開いてください。',
    source: '音声モデルと元のデータ', wav: 'WAVを開く',
  },
}

export default function IpaVoicePilot() {
  const { language } = useLanguage()
  const l = labels[language] ?? labels.en
  const ref = useRef(null)
  const [active, setActive] = useState(null)
  const [state, setState] = useState('idle')

  useEffect(() => () => {
    if (ref.current) {
      ref.current.pause()
      ref.current.removeAttribute('src')
      ref.current = null
    }
  }, [])

  const play = sample => {
    if (ref.current) {
      ref.current.pause()
      ref.current.removeAttribute('src')
      ref.current = null
    }
    if (active === sample.word && state === 'playing') {
      setActive(null)
      setState('idle')
      return
    }
    const audio = new Audio(pilotAudioUrl(sample.word))
    ref.current = audio
    setActive(sample.word)
    setState('loading')
    audio.onplaying = () => { if (ref.current === audio) setState('playing') }
    audio.onended = () => { if (ref.current === audio) { ref.current = null; setActive(null); setState('idle') } }
    const failed = () => { if (ref.current === audio) { ref.current = null; setState('error') } }
    audio.onerror = failed
    try { audio.play()?.catch(failed) } catch { failed() }
  }

  const selected = voiceSamples.find(s => s.word === active)
  return (
    <section className="ipa-voice-pilot" aria-label={l.title}>
      <div className="ipa-voice-pilot-header">
        <p className="ip-kicker">{language === 'ja' ? 'アメリカ英語 · １つの声' : 'GENERAL AMERICAN · ONE VOICE'}</p>
        <h3>{l.title}</h3>
        <p>{l.intro}</p>
      </div>
      <div className="ipa-voice-pilot-grid">
        {voiceSamples.map(sample => <button
          type="button" key={sample.word}
          className={'ipa-voice-choice' + (active === sample.word ? ' is-playing' : '')}
          aria-label={`${l.button} ${sample.word} /${sample.ipa}/`}
          aria-pressed={active === sample.word && state === 'playing'}
          onClick={() => play(sample)}>
          <span className="ipa-voice-symbol">/{sample.ipa}/</span>
          <span className="ipa-voice-word">{sample.word}</span>
          <span className="ipa-voice-action"><Glyph name="play" size={13}/>{active === sample.word && state === 'playing' ? l.stop : l.button}</span>
        </button>)}
      </div>
      <p className="ipa-voice-status" role="status" aria-live="polite">
        {state === 'error' ? l.error : state === 'playing' ? `${l.playing}: ${selected?.word}` : ''}
        {state === 'error' && selected && <a target="_blank" rel="noopener noreferrer" href={pilotAudioUrl(selected.word)}>{l.wav}</a>}
      </p>
      <p className="ipa-voice-instruction">{l.instruction}</p>
      <p className="ipa-voice-note">{l.note}</p>
      <a className="ipa-voice-source" href="https://huggingface.co/rhasspy/piper-voices/blob/main/en/en_US/ljspeech/medium/MODEL_CARD"
        target="_blank" rel="noopener noreferrer">{l.source}</a>
    </section>
  )
}
