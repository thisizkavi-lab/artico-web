export function chapter05JapaneseFor(english) {
  if (typeof english !== 'string') return '';
  const key = english.replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/\s+/g, ' ').trim();
  if (chapter05Japanese[key]) return chapter05Japanese[key];
  // Spoken prompts and printed table entries differ in terminal punctuation.
  // Restrict that equivalence to Chapter 05; never use dictionary translation.
  return chapter05Japanese[key.replace(/[.!?]+$/, '')] ||
    chapter05Japanese[key + '.'] || '';
}
